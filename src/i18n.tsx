export type TKey = keyof Dict

interface I18n {
  lang: Lang
  setLang: (l: Lang) => void
  t: (k: TKey, vars?: Record<string, string | number>) => string
  fmtDate: (iso: string, opts?: Intl.DateTimeFormatOptions) => string
}

const Ctx = createContext<I18n>(null!)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return (localStorage.getItem('lang') as Lang) || 'fr'
    } catch {
      return 'fr'
    }
  })

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
  }, [lang])

  const setLang = (l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem('lang', l)
    } catch {
      /* ignore */
    }
  }

  const dict = lang === 'ar' ? ar : fr
  const t: I18n['t'] = (k, vars) => {
    let s = dict[k] ?? fr[k] ?? k
    if (vars) for (const [n, v] of Object.entries(vars)) s = s.replace(`{${n}}`, String(v))
    return s
  }
  const fmtDate: I18n['fmtDate'] = (iso, opts = { weekday: 'short', day: 'numeric', month: 'short' }) =>
    parseISO(iso).toLocaleDateString(lang === 'ar' ? 'ar-DZ' : 'fr-FR', opts)

  return <Ctx.Provider value={{ lang, setLang, t, fmtDate }}>{children}</Ctx.Provider>
}

export const useI18n = () => useContext(Ctx)
